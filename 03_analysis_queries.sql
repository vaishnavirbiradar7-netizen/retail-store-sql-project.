-- ------------------------------------------------------------
-- 15. CASE STATEMENT: Segment customers by lifetime value
-- ------------------------------------------------------------
SELECT
    customer_id,
    first_name,
    last_name,
    lifetime_value,
    CASE
        WHEN lifetime_value >= 5000 THEN 'Gold'
        WHEN lifetime_value >= 2000 THEN 'Silver'
        WHEN lifetime_value > 0     THEN 'Bronze'
        ELSE 'No Purchases'
    END AS customer_tier
FROM customer_order_summary
ORDER BY lifetime_value DESC;
